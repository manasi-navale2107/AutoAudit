# NUMERIC SUMMARY
# ============================================================

class NumericSummary(DatasetSchema):
    """
    Summary calculated over finite numeric values only.

    NaN/missing values are counted separately.
    Positive and negative infinity are not finite values.

    Standard deviation uses the population definition (ddof=0).
    """

    finite_count: NonNegativeInt
    infinite_count: NonNegativeInt = 0

    minimum: float | None = None
    maximum: float | None = None
    mean: float | None = None
    median: float | None = None

    std: float | None = Field(
        default=None,
        ge=0.0,
    )

    @model_validator(mode="after")
    def validate_statistics(self) -> Self:
        statistics = (
            self.minimum,
            self.maximum,
            self.mean,
            self.median,
            self.std,
        )

        if self.finite_count == 0:
            if any(value is not None for value in statistics):
                raise ValueError(
                    "Numeric statistics must be null when "
                    "there are no finite values."
                )

            return self

        if any(value is None for value in statistics):
            raise ValueError(
                "All numeric statistics are required when "
                "finite_count is greater than zero."
            )

        if self.minimum > self.maximum:
            raise ValueError(
                "minimum must not exceed maximum."
            )

        if not self.minimum <= self.median <= self.maximum:
            raise ValueError(
                "median must lie between minimum and maximum."
            )

        return self



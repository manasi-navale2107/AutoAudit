"""
Dataset contracts for AutoAudit.

These schemas describe:
- Uploaded dataset metadata.
- Individual column profiles.
- Dataset-level profiling results.
- Dataset warnings.

They do not read files, modify data, or perform cleaning.

Internal filesystem paths and raw dataset rows are deliberately
excluded from API response contracts.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Annotated, Literal
from uuid import UUID

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)
from typing_extensions import Self


# ============================================================
# REUSABLE TYPES
# ============================================================

NonNegativeInt = Annotated[
    int,
    Field(strict=True, ge=0),
]

PositiveInt = Annotated[
    int,
    Field(strict=True, ge=1),
]

Ratio = Annotated[
    float,
    Field(ge=0.0, le=1.0),
]

Sha256Digest = Annotated[
    str,
    Field(pattern=r"^[a-f0-9]{64}$"),
]

ColumnName = Annotated[
    str,
    Field(min_length=1),
]


# ============================================================
# SHARED SCHEMA BASE
# ============================================================

class DatasetSchema(BaseModel):
    """
    Reject unexpected fields and non-finite numeric values.

    Strings are not automatically stripped because column names
    must match the uploaded dataset exactly.
    """

    model_config = ConfigDict(
        extra="forbid",
        allow_inf_nan=False,
        validate_default=True,
        hide_input_in_errors=True,
    )


# ============================================================
# ENUMS
# ============================================================

class DatasetStatus(str, Enum):
    UPLOADED = "uploaded"
    PROFILING = "profiling"
    PROFILED = "profiled"
    FAILED = "failed"


class ColumnKind(str, Enum):
    """
    Inferred descriptive type, not an approved modeling role.

    An identifier or target requires additional task context.
    """

    NUMERIC = "numeric"
    CATEGORICAL = "categorical"
    BOOLEAN = "boolean"
    DATETIME = "datetime"
    TEXT = "text"
    UNKNOWN = "unknown"


class WarningSeverity(str, Enum):
    INFO = "info"
    WARNING = "warning"


class DatasetWarningCode(str, Enum):
    MISSING_VALUES = "missing_values"
    DUPLICATE_ROWS = "duplicate_rows"
    CONSTANT_COLUMN = "constant_column"
    ALL_MISSING_COLUMN = "all_missing_column"
    HIGH_CARDINALITY = "high_cardinality"
    POSSIBLE_IDENTIFIER = "possible_identifier"
    POSSIBLE_DATETIME = "possible_datetime"
    INFINITE_VALUES = "infinite_values"
    MIXED_TYPES = "mixed_types"



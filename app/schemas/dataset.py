# API RESPONSE CONTRACTS
# ============================================================

class DatasetUploadResponse(DatasetSchema):
    schema_version: Literal["1.0"] = "1.0"

    dataset: DatasetMetadata


class DatasetProfileResponse(DatasetSchema):
    schema_version: Literal["1.0"] = "1.0"

    dataset: DatasetMetadata

    profile: DatasetProfile

    @model_validator(mode="after")
    def validate_dataset_reference(self) -> Self:
        if self.dataset.dataset_id != self.profile.dataset_id:
            raise ValueError(
                "Metadata and profile must belong "
                "to the same dataset."
            )

        if self.dataset.status != DatasetStatus.PROFILED:
            raise ValueError(
                "A profile response requires profiled status."
            )

        return self
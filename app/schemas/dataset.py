# COLUMN PROFILE
# ============================================================

class ColumnProfile(DatasetSchema):
    """
    Descriptive information about one column.

    unique_count excludes missing values.

    kind is an inference. It must not trigger automatic deletion,
    encoding, or target selection.

    No sample values are included in this public contract.
    """

    name: ColumnName

    pandas_dtype: str = Field(
        min_length=1,
    )

    kind: ColumnKind

    missing_count: NonNegativeInt

    unique_count: NonNegativeInt

    numeric_summary: NumericSummary | None = None

    @model_validator(mode="after")
    def validate_numeric_summary(self) -> Self:
        if self.kind == ColumnKind.NUMERIC:
            if self.numeric_summary is None:
                raise ValueError(
                    "Numeric columns require a numeric summary."
                )

        elif self.numeric_summary is not None:
            raise ValueError(
                "Only numeric columns may contain "
                "a numeric summary."
            )

        return self


# ============================================================
# WARNINGS
# ============================================================

class DatasetWarning(DatasetSchema):
    """
    A profiling observation requiring attention.

    A warning is not proof of leakage and does not authorize
    a cleaning action.
    """

    code: DatasetWarningCode

    severity: WarningSeverity = WarningSeverity.WARNING

    message: str = Field(
        min_length=1,
        max_length=2000,
    )

    columns: list[ColumnName] = Field(
        default_factory=list,
    )

    @field_validator("message")
    @classmethod
    def reject_blank_message(cls, value: str) -> str:
        if not value.strip():
            raise ValueError(
                "Warning messages must not be blank."
            )

        return value

    @field_validator("columns")
    @classmethod
    def reject_repeated_columns(
        cls,
        value: list[str],
    ) -> list[str]:
        if len(value) != len(set(value)):
            raise ValueError(
                "A warning must not repeat a column name."
            )

        return value


# ============================================================
# COMPLETE DATASET PROFILE
# ============================================================

class DatasetProfile(DatasetSchema):
    """
    Dataset-level structural profile.

    duplicate_row_count follows:
        dataframe.duplicated(keep="first").sum()

    These are repeated rows beyond their first occurrences,
    not a recommendation to delete them.

    Statistics intended for fitting preprocessing must later
    be computed from training data only.
    """

    dataset_id: UUID

    row_count: PositiveInt

    column_count: PositiveInt

    columns: list[ColumnProfile] = Field(
        min_length=1,
    )

    duplicate_row_count: NonNegativeInt = 0

    warnings: list[DatasetWarning] = Field(
        default_factory=list,
    )

    @model_validator(mode="after")
    def validate_profile_integrity(self) -> Self:
        if self.column_count != len(self.columns):
            raise ValueError(
                "column_count must match the number "
                "of column profiles."
            )

        column_names = [
            column.name
            for column in self.columns
        ]

        if len(column_names) != len(set(column_names)):
            raise ValueError(
                "Column names must be unique."
            )

        # At least one row is the first occurrence.
        if self.duplicate_row_count >= self.row_count:
            raise ValueError(
                "duplicate_row_count must be less than row_count."
            )

        for column in self.columns:
            if column.missing_count > self.row_count:
                raise ValueError(
                    "A column's missing_count must not "
                    "exceed row_count."
                )

            non_missing_count = (
                self.row_count - column.missing_count
            )

            if column.unique_count > non_missing_count:
                raise ValueError(
                    "unique_count must not exceed "
                    "the number of non-missing values."
                )

            if (
                non_missing_count > 0
                and column.unique_count == 0
            ):
                raise ValueError(
                    "A column with non-missing values "
                    "must have at least one unique value."
                )

            if column.numeric_summary is not None:
                summary = column.numeric_summary

                represented_count = (
                    summary.finite_count
                    + summary.infinite_count
                )

                if represented_count != non_missing_count:
                    raise ValueError(
                        "Finite and infinite numeric counts "
                        "must equal the non-missing row count."
                    )

        known_columns = set(column_names)

        for warning in self.warnings:
            if not set(warning.columns).issubset(known_columns):
                raise ValueError(
                    "Warnings must reference existing columns."
                )

        return self

    @property
    def missing_cell_count(self) -> int:
        return sum(
            column.missing_count
            for column in self.columns
        )

    @property
    def missing_cell_ratio(self) -> float:
        total_cells = self.row_count * self.column_count

        return self.missing_cell_count / total_cells



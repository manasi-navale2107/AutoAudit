class DatasetMetadata(DatasetSchema):
    """
    Public dataset metadata.

    dataset_id is generated by the backend.

    original_filename is display metadata only. Never use it
    directly to construct a storage path.

    sha256 is calculated from the original uploaded file bytes.
    """

    dataset_id: UUID

    original_filename: str = Field(
        min_length=1,
        max_length=255,
    )

    file_format: Literal["csv"] = "csv"

    size_bytes: PositiveInt

    sha256: Sha256Digest

    status: DatasetStatus = DatasetStatus.UPLOADED

    uploaded_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    @field_validator("original_filename")
    @classmethod
    def validate_display_filename(cls, value: str) -> str:
        if not value.strip():
            raise ValueError(
                "The original filename must not be blank."
            )

        if "/" in value or "\\" in value:
            raise ValueError(
                "Provide a filename without directory components."
            )

        if any(
            ord(character) < 32 or ord(character) == 127
            for character in value
        ):
            raise ValueError(
                "The filename must not contain control characters."
            )

        if not value.lower().endswith(".csv"):
            raise ValueError(
                "Only CSV filenames are supported."
            )

        return value

    @field_validator("uploaded_at")
    @classmethod
    def validate_timestamp(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError(
                "uploaded_at must include timezone information."
            )

        return value.astimezone(timezone.utc)


